export function getMoveEffectiveness(moveType: MonsterType, defenderType: MonsterType): number {
  return typeEffectiveness[moveType]?.[defenderType] ?? 1;
}

export function calculateDamage(attacker: Monster, defender: Monster, move: Move): { damage: number; effectiveness: number } {
  const effectiveness = getMoveEffectiveness(move.type, defender.type);

  // Se la mossa ha power = 0, è una mossa di stato e non fa danno
  if (move.power === 0) {
    return { damage: 0, effectiveness: 1 };
  }

  const stab = attacker.type === move.type ? 1.3 : 1;
  const random = 0.85 + Math.random() * 0.15;
  const levelMod = (2 * attacker.level / 5 + 2);
  const rawDamage = (levelMod * move.power * (attacker.stats.attack / defender.stats.defense)) / 50 + 2;
  const damage = Math.max(1, Math.floor(rawDamage * stab * effectiveness * random));
  return { damage, effectiveness };
}

export function generateEnemyMonster(waveNumber: number, maxLevel?: number): Monster {
  // waveNumber qui è il numero totale di nodi affrontati: sblocca i nuovi
  // stadi dopo 10 mappe (100 nodi) e un altro stadio dopo 20 mappe.
  const difficultyTier = Math.floor(waveNumber / 100);
  const maxTier = difficultyTier >= 2 ? 3 : difficultyTier >= 1 ? 2 : 1;
  const pool = wildMonsters.filter(m => (m.tier ?? 1) <= maxTier);
  const base = pool[Math.floor(Math.random() * pool.length)];

  // L'inizio resta accessibile; dopo ogni blocco di 10 mappe cresce anche
  // il tasso di scaling, invece di aumentare bruscamente dopo il 1° blocco.
  const levelBoost = Math.floor(waveNumber * (0.18 + difficultyTier * 0.025));
  const hpBoost = Math.floor(waveNumber * (0.25 + difficultyTier * 0.05));
  const statBoost = Math.floor(waveNumber * (0.06 + difficultyTier * 0.015));

  let finalLevel = base.level + levelBoost;
  let hpMult = 1;
  let statMult = 1;

  if (maxLevel && finalLevel > maxLevel) {
    const ratio = maxLevel / finalLevel;
    finalLevel = maxLevel;
    hpMult = ratio;
    statMult = ratio;
  }

  return {
    ...base,
    level: finalLevel,
    exp: 0,
    expToNext: 20 + waveNumber * 5,
    stats: {
      hp: Math.max(10, Math.floor((base.stats.maxHp + hpBoost) * hpMult)),
      maxHp: Math.max(10, Math.floor((base.stats.maxHp + hpBoost) * hpMult)),
      attack: Math.max(3, Math.floor((base.stats.attack + statBoost) * statMult)),
      defense: Math.max(2, Math.floor((base.stats.defense + Math.floor(statBoost * 0.7)) * statMult)),
      speed: Math.max(3, Math.floor((base.stats.speed + Math.floor(statBoost * 0.5)) * statMult)),
    },
    status: [],
  };
}

